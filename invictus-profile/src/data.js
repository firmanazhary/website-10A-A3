export function generatePiketSchedule(members) {
  const activeMembers = members.filter((m) => m.status === "Aktif");

  const days = [
    { dayIndex: 1, day: "Senin", code: "MON // SECTOR 01", count: 6 },
    { dayIndex: 2, day: "Selasa", code: "TUE // SECTOR 02", count: 6 },
    { dayIndex: 3, day: "Rabu", code: "WED // SECTOR 03", count: 5 },
    { dayIndex: 4, day: "Kamis", code: "THU // SECTOR 04", count: 5 },
    { dayIndex: 5, day: "Jumat", code: "FRI // SECTOR 05", count: 5 },
  ];

  let cursor = 0;
  return days.map((slot) => {
    const assigned = activeMembers.slice(cursor, cursor + slot.count);
    cursor += slot.count;
    return {
      ...slot,
      members: assigned,
    };
  });
}

